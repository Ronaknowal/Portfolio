const capture = async (locator, name) => {
  const file = `docs/teaching/evidence/screenshots/classical-final-${name}.png`;
  await locator.screenshot({ path: file }); report.screenshots.push(file);
};
const fill = async (root, label, value) => {
  const field = root.getByLabel(label, { exact: false });
  await field.fill(String(value)); await field.blur();
};
const predict = async (box, choice, number, button = 'Apply and check') => {
  await box.locator(`input[type=radio][value="${choice}"]`).check();
  if (number !== undefined) await box.locator('input[type=number]').fill(String(number));
  await box.getByRole('button', { name: button, exact: true }).click();
};
