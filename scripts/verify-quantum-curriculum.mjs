import assert from "node:assert/strict";
import fs from "node:fs";
import { createHash } from "node:crypto";
import { trackDefinitions } from "../src/learn/data/track-definitions.js";
import { topicCatalogue } from "../src/learn/data/curriculum/topic-catalogue.js";
import { slugify } from "../src/learn/data/topic-id.js";
import { learningPaths, getLearningRoute } from "./lib/authoring-curriculum.mjs";

const baseline = JSON.parse(fs.readFileSync("docs/curriculum/quantum-curriculum-baseline.json", "utf8"));
const manifest = JSON.parse(fs.readFileSync("src/learn/data/lesson-manifest.json", "utf8"));
const originalIds = new Set(baseline.topicIds);
const track = trackDefinitions.find(track => track.id === "quantum-ai");
const topics = track.sections.flatMap(section => section.topics);
const positions = new Map(topics.map((topic, position) => [slugify(topic.title), position]));
const previous = baseline.modules.find(module => module.id === track.id);
const retained = previous.sections.flatMap(section => section.titles);

for (const id of originalIds) assert.ok(topicCatalogue[id], `Existing topic removed: ${id}`);
for (const title of retained) assert.ok(positions.has(slugify(title)), `Existing quantum topic removed: ${title}`);
assert.equal(positions.size, topics.length, "Duplicate quantum topic identity");
for (const section of track.sections) {
  assert.ok(section.topics.length >= 5, `Unnecessarily fragmented section: ${section.name}`);
  for (const topic of section.topics) {
    const id = slugify(topic.title);
    const record = topicCatalogue[id];
    assert.ok(topic.subtopics?.length >= 3, `Missing named coverage: ${id}`);
    assert.equal(new Set(topic.subtopics).size, topic.subtopics.length, `Repeated named concept: ${id}`);
    assert.equal(record.prerequisiteStatus, "recorded", `Prerequisite review missing: ${id}`);
    for (const prerequisite of record.prerequisiteIds) {
      assert.ok(topicCatalogue[prerequisite], `Unresolved prerequisite: ${prerequisite}`);
      if (positions.has(prerequisite)) assert.ok(positions.get(prerequisite) < positions.get(id), `Forward prerequisite: ${id} -> ${prerequisite}`);
    }
    if (!originalIds.has(id)) {
      assert.ok(topic.blueprint?.sequence.length >= 4, `Missing scoped teaching sequence: ${id}`);
      assert.ok(topic.blueprint.visual.question && topic.blueprint.practice.success && topic.blueprint.misconceptions.length, `Incomplete teaching brief: ${id}`);
      for (const url of topic.blueprint.sources) assert.equal(new URL(url).protocol, "https:");
    }
  }
}
for (const pathId of ["quantum-computing", "full-curriculum"]) {
  const path = learningPaths.find(path => path.id === pathId);
  assert.ok(path, `Missing route: ${pathId}`);
  const route = getLearningRoute(path);
  assert.deepEqual(route.navigationGroups.find(group => group.id === track.id).topicIds, [...positions.keys()]);
  for (const id of route.topicIds) for (const prerequisite of topicCatalogue[id].prerequisiteIds) {
    assert.ok(route.topicIds.includes(prerequisite), `Missing route dependency: ${id} -> ${prerequisite}`);
  }
}

// This boundary applies to the catalogue expansion only. A later authorized
// lesson publication must not be blocked by historical snapshot hashes.
if (process.argv.includes("--check-planning-boundary")) {
  for (const [filename, expected] of Object.entries(baseline.unchangedFiles)) {
    assert.equal(createHash("sha256").update(fs.readFileSync(filename)).digest("hex"), expected, `Changed delivery/publication: ${filename}`);
  }
  for (const module of baseline.modules.filter(module => module.id !== track.id)) {
    const current = trackDefinitions.find(track => track.id === module.id);
    assert.deepEqual(current.sections.map(section => ({ name: section.name, titles: section.topics.map(topic => topic.title) })), module.sections, `Unrelated module altered: ${module.id}`);
  }
  for (const id of positions.keys()) assert.ok(!manifest[id], `Curriculum planning published a quantum lesson: ${id}`);
}

if (process.argv.includes("--write-syllabus")) {
  const lines = [
    `# ${track.title}: detailed syllabus`, "",
    "Generated by `node scripts/verify-quantum-curriculum.mjs --write-syllabus` from the live catalogue. Do not edit this derived list independently.", "",
    "See [scope, role routes and teaching instructions](QUANTUM-COMPUTING-PLAN.md). Named concepts are planned teaching obligations, not completed content. The order below is the module's reading order; specialist branches are deliberate depth.", "",
  ];
  let position = 0;
  for (const section of track.sections) {
    lines.push(`## ${section.name}`, "");
    for (const topic of section.topics) {
      const id = slugify(topic.title);
      const blueprint = topic.blueprint;
      lines.push(`### ${++position}. ${topic.title}`, "",
        `- Stable ID: \`${id}\`. Level: ${topic.level}; ${originalIds.has(id) ? "retained" : "new"} planned topic.`,
        `- Named concept coverage: ${topic.subtopics.join("; ")}.`,
        `- Prerequisites: ${topicCatalogue[id].prerequisiteIds.map(id => topicCatalogue[id].title).join("; ") || "Start here; no topic prerequisites"}.`);
      if (blueprint) {
        lines.push(`- Learning sequence: ${blueprint.sequence.join("; ")}.`,
          `- Investigation: ${blueprint.visual.type}. ${blueprint.visual.question} ${blueprint.visual.interaction}.`,
          `- Practice: ${blueprint.practice.task}. Success: ${blueprint.practice.success}.`,
          `- Research starting points: ${blueprint.sources.join("; ")}.`);
      } else lines.push("- Detailed design: still needed. Retain the named concepts and build a complete topic-specific brief during an authorized research/write or full request.");
      if (topic.scopeNote) lines.push(`- Authoring scope note: ${topic.scopeNote}`);
      lines.push("");
    }
  }
  fs.writeFileSync("docs/curriculum/QUANTUM-COMPUTING-SYLLABUS.md", lines.join("\n"));
}
console.log(JSON.stringify({ status: "passed", module: track.title, topics: topics.length, retained: retained.length,
  added: topics.filter(topic => !originalIds.has(slugify(topic.title))).length, sections: track.sections.length,
  namedConceptLabels: topics.reduce((sum, topic) => sum + topic.subtopics.length, 0),
  originalCatalogueTopicsPreserved: originalIds.size, totalTopics: Object.keys(topicCatalogue).length,
  planningBoundaryChecked: process.argv.includes("--check-planning-boundary") }, null, 2));
