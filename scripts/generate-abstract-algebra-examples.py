import black

ROOT = Path(__file__).resolve().parents[1]
examples = []


def add(identifier, title, question, code):
    source = textwrap.dedent(code).strip() + "\n"
    formatted = black.format_str(source, mode=black.Mode(line_length=80))
    assert ast.dump(ast.parse(source)) == ast.dump(ast.parse(formatted))
    output = io.StringIO()
    with contextlib.redirect_stdout(output):
        exec(compile(formatted, identifier, "exec"), {})
    examples.append({"id": identifier, "title": title, "question": question,
                     "code": formatted, "expected": output.getvalue().strip(),
                     "environment": "Python 3.12; standard library"})


GROUP = '''
NAMES = ["e", "r", "r^2", "r^3", "s", "rs", "r^2s", "r^3s"]
G = range(8)

def compose(g, h):
    # gh means apply h first, then g. Encode r^k s^b by k+4b.
    k, b = g % 4, g // 4
    l, c = h % 4, h // 4
    return (k + (-1)**b * l) % 4 + 4*(b ^ c)

def image(g, i):
    return (g % 4 + (-1)**(g // 4)*i) % 4

def inverse(g):
    return next(h for h in G if compose(g, h) == compose(h, g) == 0)

def move(g, values):
    if len(values) != 4:
        raise ValueError("Supply all four vertex values")
    result = [None]*4
    for i, value in enumerate(values):
        result[image(g, i)] = value
    return tuple(result)
'''

add("composition", "Track a label through both orders", "Starting at vertex 1, do rs and sr finish at the same vertex?", GROUP + '''
g, h, vertex = 1, 4, 1
for outer, inner in [(g,h), (h,g)]:
    product = compose(outer,inner)
    print(NAMES[product], "path:", [vertex,image(inner,vertex),image(product,vertex)])
    print("labels at positions 0..3:", " ".join(move(product,"ABCD")))
    print("inverse:",NAMES[inverse(product)])
''')

add("laws", "Identify all square symmetries and check the finite laws", "Why does preserving distances select only eight of the 24 vertex permutations?", GROUP + '''
from itertools import permutations, product
vertices = [(1,0),(0,1),(-1,0),(0,-1)]
def distance_squared(i,j):
    return sum((a-b)**2 for a,b in zip(vertices[i],vertices[j]))
symmetries = [p for p in permutations(range(4)) if all(
    distance_squared(i,j) == distance_squared(p[i],p[j])
    for i,j in product(range(4),repeat=2))]
encoded = {tuple(image(g,i) for i in range(4)) for g in G}
print("distance-preserving permutations:",len(symmetries))
print("same as encoded maps:",set(symmetries)==encoded)
print("associative triples:",sum(compose(compose(g,h),k)==compose(g,compose(h,k))
    for g,h,k in product(G,repeat=3)))
print("two-sided inverse pairs:",sum(compose(g,inverse(g))==compose(inverse(g),g)==0 for g in G))
print("noncommuting witness:",NAMES[compose(1,4)],"!=",NAMES[compose(4,1)])
''')

COSETS = '''
def left_coset(g,H):
    return frozenset(compose(g,h) for h in H)

def cosets(H):
    result=[]
    for g in G:
        value=left_coset(g,H)
        if value not in result:
            result.append(value)
    return result

def names(values):
    return "{"+", ".join(NAMES[g] for g in sorted(values))+"}"
'''

add("subgroups", "Generate a subgroup and partition the group", "What subgroup is generated by a half-turn, and how many translated copies fit in D4?", GROUP + COSETS + '''
def generated(generators):
    found={0}
    frontier=[0]
    while frontier:
        current=frontier.pop()
        for g in generators:
            value=compose(g,current)
            if value not in found:
                found.add(value)
                frontier.append(value)
    return found

H=generated([2])
print("generated by r^2:",names(H))
print("left cosets:"," | ".join(names(c) for c in cosets(H)))
print("group size:",len(cosets(H)),"*",len(H),"=",len(G))
print("generated by r and s:",names(generated([1,4])))
''')

add("orbits", "Count colorings two independent ways", "With three named colors, does allowing reflection merge any rotation-only classes?", GROUP + '''
from itertools import product

def orbits(q,group):
    unseen=set(product(range(q),repeat=4))
    result=[]
    while unseen:
        state=min(unseen)
        orbit={move(g,state) for g in group}
        result.append(orbit)
        unseen.difference_update(orbit)
    return result

def cycle_count(g):
    unseen=set(range(4))
    count=0
    while unseen:
        start=min(unseen)
        current=start
        while current in unseen:
            unseen.remove(current)
            current=image(g,current)
        count+=1
    return count

state=(1,0,1,0)
print("opposite-mark orbit:",sorted({move(g,state) for g in G}))
print("stabilizer:",[NAMES[g] for g in G if move(g,state)==state])
for q in [2,3]:
    fixed=[q**cycle_count(g) for g in G]
    classes=orbits(q,G)
    print("colors",q,"fixed counts",fixed)
    print("Burnside / enumeration:",sum(fixed)//len(G),len(classes))
    print("rotations only:",len(orbits(q,range(4))))
''')

add("quotients", "Check representative independence directly", "Why can the rotation subgroup be collapsed while {e,s} fails the same multiplication rule?", GROUP + COSETS + '''
def representative_independent(H):
    for g in G:
        for h in G:
            expected=left_coset(compose(g,h),H)
            for a in left_coset(g,H):
                for b in left_coset(h,H):
                    if left_coset(compose(a,b),H)!=expected:
                        return False
    return True

N={0,1,2,3}; H={0,4}
print("rotations give a well-defined product:",representative_independent(N))
print("{e,s} gives a well-defined product:",representative_independent(H))
print("same input coset:",names(left_coset(0,H)),names(left_coset(4,H)))
print("using e then right factor r:",names(left_coset(compose(0,1),H)))
print("using s then right factor r:",names(left_coset(compose(4,1),H)))
print("orientation preserves every product:",all(
    (-1)**(compose(g,h)//4)==(-1)**(g//4)*(-1)**(h//4) for g in G for h in G))
''')

MATRICES = '''
from fractions import Fraction

def matmul(A,B):
    return [[sum(A[i][k]*B[k][j] for k in range(len(B)))
        for j in range(len(B[0]))] for i in range(len(A))]

def matvec(A,x):
    return tuple(sum(a*b for a,b in zip(row,x)) for row in A)

def P(g):
    return [[int(j==image(g,i)) for i in range(4)] for j in range(4)]

def defect(W,g):
    left,right=matmul(W,P(g)),matmul(P(g),W)
    return max(abs(left[i][j]-right[i][j]) for i in range(4) for j in range(4))

def averaged(W,group=range(8)):
    group=tuple(group)
    result=[[Fraction(0) for _ in range(4)] for _ in range(4)]
    for g in group:
        term=matmul(matmul(P(inverse(g)),W),P(g))
        for i in range(4):
            for j in range(4):
                result[i][j]+=Fraction(term[i][j],len(group))
    return result
'''

add("representations", "One group, two different kinds of vector", "Does a scalar nonlinearity commute with both vertex permutations and geometric reflections?", GROUP + MATRICES + '''
vertices=[(1,0),(0,1),(-1,0),(0,-1)]
def R(g):
    x,y=vertices[image(g,0)],vertices[image(g,1)]
    return [[x[0],y[0]],[x[1],y[1]]]
print("geometric r:",R(1))
print("data permutation r:",P(1))
print("both preserve all 64 products:",all(
    matmul(R(g),R(h))==R(compose(g,h)) and
    matmul(P(g),P(h))==P(compose(g,h)) for g in G for h in G))
relu=lambda x:tuple(max(0,v) for v in x)
data=(-2,1,-3,4)
print("ReLU and every data permutation:",all(relu(move(g,data))==move(g,relu(data)) for g in G))
point=(-1,2); reflection=[[-1,0],[0,1]]
print("geometric reflect then ReLU:",relu(matvec(reflection,point)))
print("ReLU then geometric reflect:",matvec(reflection,relu(point)))
''')

