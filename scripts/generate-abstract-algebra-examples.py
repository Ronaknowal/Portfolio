add("modular", "Division depends on the arithmetic structure", "How many solutions does 2x=4 have modulo 5, 6 and 8?", '''
from math import gcd

def solve_congruence(a,b,n):
    if any(type(v) is not int for v in (a,b,n)) or not 2<=n<=100:
        raise ValueError("Use integer coefficients and a modulus from 2 to 100")
    return [x for x in range(n) if (a*x-b)%n==0]

for n in [5,6,8]:
    units=[a for a in range(n) if any(a*x%n==1 for x in range(n))]
    print("modulus",n,"units:",units)
    print("2x=4 solutions:",solve_congruence(2,4,n))
    print("unit/gcd test agrees:",units==[a for a in range(n) if gcd(a,n)==1])
print("zero-divisor witness mod 6:",2*3%6)
''')

