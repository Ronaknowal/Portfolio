// Rebuild only this lesson's on-demand measured-data module and offline assets.
import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd(),
  draft = path.join(root, 'docs/teaching/drafts/perceptrons-neurons-activation-functions');
const record = JSON.parse(fs.readFileSync(path.join(draft, 'calculated-inputs.json'), 'utf8'));
const lines = fs.readFileSync(path.join(draft, 'digits-400.csv'), 'utf8').trim().split(/\r?\n/),
  headers = lines.shift().split(',');
const digits = lines.map(line => {
  const values = line.split(',').map(Number),
    row = Object.fromEntries(headers.map((h, i) => [h, values[i]]));
  return {
    sourceId: row.source_id,
    digit: row.digit,
    pixels: Array.from({
      length: 64
    }, (_, i) => row[`pixel_${i}`])
  };
});
const byId = new Map(digits.map(row => [row.sourceId, row]));
const runs = record.digitComparison.map(row => ({
  ...row,
  correct: row.validationPredictions.filter((prediction, i) => prediction === byId.get(record.digitSplits.validationSourceIds[i]).digit).length
}));
fs.writeFileSync(path.join(root, 'src/learn/data/perceptron-data.js'), `// Actual retained UCI images and measured CPU runs; generated by scripts/build-perceptron-data.mjs.\nexport const perceptronData = ${JSON.stringify({
  versions: record.versions,
  digits,
  runs,
  splits: record.digitSplits
})};\n`);
const assets = path.join(root, 'public/learn-assets/perceptrons');
fs.mkdirSync(assets, {
  recursive: true
});
for (const filename of ['digits-400.csv', 'data-provenance.md']) fs.copyFileSync(path.join(draft, filename), path.join(assets, filename));
console.log(`Wrote ${digits.length} observed images and ${runs.length} measured activation runs.`);
