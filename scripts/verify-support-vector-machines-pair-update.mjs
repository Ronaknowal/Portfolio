// Focused closure for flat/linear pair directions; preserves unrelated program evidence.
import fs from 'node:fs';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { svmPairStep } from '../src/learn/data/support-vector-machines-models.js';
import { svmExamples } from '../src/learn/data/support-vector-machines-examples.js';
const directory = 'scratch/support-vector-machines-verification';
const cases = [];
for (const alpha of [[.4, .1, .3], [.4, .4, 0], [.4, 0, .4]]) {
  const points = [[-1, 0], [1, 0], [1, 0]], labels = [-1, 1, 1];
  const result = svmPairStep(points, labels, alpha, 1, 1, 2);
  assert.equal(result.q, 0); assert.equal(result.g, 0); assert.equal(result.bestDelta, 0);
  assert.deepEqual(result.after, alpha);
  cases.push({ points, labels, alpha, c: 1, i: 1, j: 2, result });
}
for (const c of [.05, .7, 1.2, 4]) {
  const points = [[0, 0], [0, 0]], labels = [-1, 1], alpha = [0, 0];
  const result = svmPairStep(points, labels, alpha, c, 0, 1);
  assert.deepEqual(result.after, [c, c]); assert.equal(result.improvement, 2*c);
  cases.push({ points, labels, alpha, c, i: 0, j: 1, result });
}
const run = spawnSync('scratch/lesson-tools/Scripts/python.exe', ['-c', `
import contextlib, io, json, runpy, sys
import numpy as np
path='scripts/support-vector-machines-programs/pair-move.py'
stream=io.StringIO()
with contextlib.redirect_stdout(stream):
    namespace=runpy.run_path(path,run_name='__main__')
cases=json.load(sys.stdin)
for case in cases:
    answer=namespace['pair_move'](np.array(case['points'],dtype=float),np.array(case['labels']),np.array(case['alpha'],dtype=float),case['c'],case['i'],case['j'])
    assert np.array_equal(answer[0],np.array(case['result']['after']))
    assert abs(answer[-1]-case['result']['improvement'])<1e-12
print(json.dumps({'stdout':stream.getvalue().strip(),'cases':len(cases)}))
`], { input: JSON.stringify(cases), encoding: 'utf8', timeout: 30000 });
assert.equal(run.status, 0, run.stderr);
const result = JSON.parse(run.stdout);
assert.equal(result.stdout, svmExamples.pair.expected);
const source = 'scripts/support-vector-machines-programs/pair-move.py';
const previous = { code: svmExamples.pair.code, expected: svmExamples.pair.expected };
svmExamples.pair.code = fs.readFileSync(source, 'utf8').trim();
fs.writeFileSync('src/learn/data/support-vector-machines-examples.js', '// Generated by scripts/build-support-vector-machines-examples.py from executed complete programs.\nexport const svmExamples = '+JSON.stringify(svmExamples,null,2)+';\n');
const records = JSON.parse(fs.readFileSync(`${directory}/program-results.json`));
const entry = records.programs.find(program => program.key === 'pair');
const beforeHash = entry.sha256;
entry.sha256 = crypto.createHash('sha256').update(fs.readFileSync(source)).digest('hex');
entry.executedAt = new Date().toISOString();
records.amendments = [...(records.amendments || []), { key: 'pair', executedAt: entry.executedAt, beforeHash, reason: 'Flat q=g=0 tie now leaves both coefficients unchanged; actual stdout unchanged.' }];
fs.writeFileSync(`${directory}/program-results.json`,JSON.stringify(records,null,2)+'\n');
fs.writeFileSync(`${directory}/pair-update-results.json`,JSON.stringify({ executedAt: entry.executedAt, cases, previous, stdout: result.stdout, sourceHash: entry.sha256, unchangedOtherProgramCount: 13 },null,2)+'\n');
console.log(`Passed ${cases.length} JS/native pair cases; actual standalone stdout unchanged; thirteen other programs retained.`);
