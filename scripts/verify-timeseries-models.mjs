/* ======================================= second routes, written from scratch */

/** The seasonal rule by MATERIALISING the final observed cycle and walking
 *  round it. Nothing to do with the index formula the module evaluates. */
function seasonalByCycle(history, period, horizon) {
  const cycle = history.slice(history.length - period);
  assert.equal(cycle.length, period, 'the materialised cycle is the wrong length');
  const out = [];
  let position = 0;
  for (let lead = 1; lead <= horizon; lead += 1) {
    out.push(cycle[position]);
    position = (position + 1) % period;
  }
  return out;
}

/** The other three rules by plain accumulation. */
function rulesByLoops(history, period, horizon) {
  let total = 0;
  for (const value of history) total += value;
  const mean = total / history.length;
  const last = history[history.length - 1];
  const slope = (last - history[0]) / (history.length - 1);
  const drift = [];
  for (let lead = 1; lead <= horizon; lead += 1) drift.push(last + lead * slope < 0 ? 0 : last + lead * slope);
  return {
    mean: Array.from({ length: horizon }, () => mean),
    naive: Array.from({ length: horizon }, () => last),
    seasonal: seasonalByCycle(history, period, horizon),
    drift,
  };
}

/**
 * Availability as a SET, not as an inequality.
 *
 * Walks the calendar forward and records, for each day, which observation dates
 * have actually turned up by then under the reporting delay. A row is eligible
 * when the observation it needs as a label is a member of that set. This cannot
 * share a bug with `s + h + d <= cutoff`, because it never writes that
 * expression.
 */
function knownByDay(lastDay, delay) {
  const known = new Map();
  for (let day = 0; day <= lastDay; day += 1) {
    const arrived = new Set();
    for (let observation = 0; observation <= day; observation += 1) {
      if (observation + delay <= day) arrived.add(observation);
    }
    known.set(day, arrived);
  }
  return known;
}

function eligibleBySets(origins, cutoff, horizon, delay) {
  const known = knownByDay(Math.max(cutoff, ...origins) + horizon + delay + 2, delay);
  const arrivedByCutoff = known.get(cutoff);
  return origins.filter(origin => arrivedByCutoff.has(origin + horizon));
}

/**
 * A split schedule built by SIMULATING THE CALENDAR FORWARD.
 *
 * At each issue day it collects the rows whose label has already turned up,
 * rather than computing a last-eligible index. The two routes must agree on the
 * exact list of training origins, not merely on how many there are.
 */
function scheduleBySimulation({ issueOrigin, horizon, firstTrainOrigin, delay, window }) {
  const known = knownByDay(issueOrigin + horizon + delay + 2, delay);
  const arrived = known.get(issueOrigin);
  const rows = [];
  for (let origin = firstTrainOrigin; origin <= issueOrigin; origin += 1) {
    if (arrived.has(origin + horizon)) rows.push(origin);
  }
  return window === null || window === undefined ? rows : rows.slice(Math.max(0, rows.length - window));
}

/** The served CSV, parsed here rather than taken from the generated module. */
function readServedSeries() {
  const text = fs.readFileSync('public/learn-assets/time-series-validation/bike-sharing-daily.csv', 'utf8');
  const lines = text.trim().split(/\r?\n/);
  const header = lines[0].split(',');
  const dateColumn = header.indexOf('dteday');
  const countColumn = header.indexOf('cnt');
  const casualColumn = header.indexOf('casual');
  const registeredColumn = header.indexOf('registered');
  assert.ok(dateColumn >= 0 && countColumn >= 0, 'the served CSV has no dteday or cnt column');
  const rows = lines.slice(1).map(line => line.split(','));
  return {
    dates: rows.map(row => row[dateColumn]),
    counts: rows.map(row => Number(row[countColumn])),
    casual: rows.map(row => Number(row[casualColumn])),
    registered: rows.map(row => Number(row[registeredColumn])),
    sha256: crypto.createHash('sha256')
      .update(fs.readFileSync('public/learn-assets/time-series-validation/bike-sharing-daily.csv')).digest('hex'),
  };
}

