/** The manuscript prints rounded values. The honest check is not a tolerance
 *  but the rounding property itself: the typed value must be A valid rounding
 *  of the computed one at the number of decimals the manuscript shows. A
 *  tolerance loose enough to accept 931.875 as 931.88 would also accept a
 *  genuinely different number, and one tight enough to reject that would
 *  reject a correct value. */
const printsAs = (actual, printed, decimals, label) => {
  assert(typeof actual === 'number' && Number.isFinite(actual), `${label}: ${actual} is not a finite number`);
  const halfStep = 0.5 * 10 ** -decimals;
  assert(Math.abs(actual - printed) <= halfStep + 1e-9,
    `${label}: the manuscript prints ${printed} at ${decimals} decimals, but the value is ${actual}`);
};

