// Bounded independent checks of the forecasting browser models against the
// content packet's recorded calculations, the manuscript's stated values, the
// served dataset, and a second construction for every rule a figure draws.
//
// Every assertion here is written so that it can fail: nothing is compared with
// itself, no loop is allowed to inspect an empty subject set, and every group
// asserts how many subjects it actually saw.
//
// Four rules shaped this file.
//
//   1. A SECOND ROUTE MEANS A DIFFERENT CONSTRUCTION. The seasonal rule is
//      checked against a route that MATERIALISES the final observed cycle and
//      walks round it, never against the index formula the module uses.
//      Eligibility is checked against a route that materialises the SET OF
//      OBSERVATIONS KNOWN AT EACH DAY and asks whether the row's label is in it
//      -- availability as a set, not as an inequality. Split schedules are
//      generated by simulating the calendar forward day by day, not by calling
//      the module's own generator. The real numbers are recomputed from the
//      served CSV, parsed here.
//
//   2. THE RULE DRAWN MUST EQUAL THE RULE APPLIED ACROSS THE WHOLE ENTERABLE
//      GRID. Investigation 2's eligibility verdict is swept over every cutoff,
//      horizon, delay and origin its controls admit. Investigation 1's donor is
//      swept over every season length, horizon count and inspected horizon.
//      Investigation 3's comparison is swept over every offered origin and
//      season length. Not samples of them: a lab that grades a correct answer
//      wrong is the defect class this repository is most exposed to.
//
//   3. NO FITTED WINDOW MAY CONTAIN AN OBSERVATION LATER THAN ITS OWN ORIGIN.
//      This is the topic's own invariant and it is asserted three ways --
//      feature causality against each row's own origin, label maturity against
//      the fit's origin, and closure of the whole fit -- over every split the
//      lesson draws and every split a control can produce. The audit is itself
//      falsified below with a deliberately invalid fit, because an audit that
//      always returns clean is not an audit.
//
//   4. EVERY GRADED COMPARISON IS EXERCISED AT ITS DEGENERATE INPUTS. An
//      unscored horizon, an empty eligible set, a season length of one (which
//      makes the seasonal rule EXACTLY the naive rule, so the comparison must
//      return a tie rather than a near miss), a horizon past the supplied
