import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "@babel/parser";
import { topicCatalogue } from "../src/learn/data/curriculum/topic-catalogue.js";
import { trackDefinitions } from "../src/learn/data/track-definitions.js";
import { buildTracks } from "../src/learn/data/curriculum/track-structure.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dataDirectory = path.join(root, "src/learn/data");
const outputDirectory = path.join(dataDirectory, "generated");
const checkOnly = process.argv.includes("--check");
const manifest = JSON.parse(fs.readFileSync(path.join(dataDirectory, "lesson-manifest.json"), "utf8"));
const outputs = new Map();

// Parse only static metadata. Never execute lesson components or their imports
// in authoring tools, or bundle them into search/navigation data.
function readLessonMetadata(id, relativePath) {
  if (!/^\.\/topics\/[a-z0-9-]+\.jsx$/.test(relativePath)) throw new Error(`Invalid lesson path: ${id}: ${relativePath}`);
  if (!topicCatalogue[id]) throw new Error(`Published lesson has no catalogue entry: ${id}`);
  const source = fs.readFileSync(path.join(dataDirectory, relativePath), "utf8");
  const { program } = parse(source, { sourceType: "module", plugins: ["jsx"] });
  const declarations = new Map();
  for (const statement of program.body) {
    if (statement.type === "VariableDeclaration") {
      for (const declaration of statement.declarations) declarations.set(declaration.id.name, declaration.init);
    }
  }
  let definition = program.body.find(statement => statement.type === "ExportDefaultDeclaration")?.declaration;
  if (definition?.type === "Identifier") definition = declarations.get(definition.name);
  if (definition?.type !== "ObjectExpression") throw new Error(`${id}: default export must be a lesson object`);
  const properties = new Map(definition.properties.map(property => [property.key?.name ?? property.key?.value, property.value]));
  const metadata = {};
  for (const field of ["title", "readTime", "hasIntegratedGuide"]) {
    const value = properties.get(field);
    if (!value && field === "hasIntegratedGuide") continue;
    const expected = field === "hasIntegratedGuide" ? "BooleanLiteral" : "StringLiteral";
    if (value?.type !== expected) throw new Error(`${id}: ${field} must be a static ${expected}`);
    metadata[field] = value.value;
  }
  if (!properties.has("content")) throw new Error(`${id}: missing lesson content`);
  return metadata;
}

const lessonMetadata = Object.fromEntries(Object.entries(manifest).map(([id, relativePath]) => [id, readLessonMetadata(id, relativePath)]));
if (new Set(Object.values(manifest)).size !== Object.keys(manifest).length) throw new Error("Each published topic must have its own lesson source");
// Explicit imports keep unregistered drafts outside the production build too.
outputs.set("lesson-imports.js", "// Generated from lesson-manifest.json. Do not edit.\nexport const lessonModules = {\n" +
  Object.entries(manifest).map(([id, relativePath]) => `  ${JSON.stringify(id)}: () => import(${JSON.stringify(relativePath.replace("./topics/", "../topics/"))}),`).join("\n") + "\n};\n");
const allTopicsOrdered = Object.values(topicCatalogue).map((topic, order) => {
  const lesson = lessonMetadata[topic.id];
  if (topic.blueprint && !lesson) {
    const { summary, outcomes, sequence, visual, practice, sources } = topic.blueprint;
    outputs.set(`outlines/${topic.id}.json`, JSON.stringify({ summary, outcomes, sequence,
      visual: { question: visual.question, interaction: visual.interaction },
      practice: { task: practice.task, success: practice.success }, sources }) + "\n");
  }
  return {
    id: topic.id, title: lesson?.title ?? topic.title, category: topic.trackId,
    trackId: topic.trackId, trackIds: topic.trackIds, level: topic.level || "foundation",
    section: topic.section, readTime: lesson?.readTime ?? "Syllabus outline",
    prerequisiteIds: topic.prerequisiteIds, designStatus: topic.designStatus,
    depth: topic.blueprint?.depth ?? null, hasOutline: Boolean(topic.blueprint && !lesson),
    hasIntegratedGuide: lesson?.hasIntegratedGuide === true, status: lesson ? "published" : "planned", order,
  };
});
outputs.set("navigation.js", "// Generated by scripts/generate-learning-artifacts.mjs. Do not edit.\n" +
  `export const allTopicsOrdered = ${JSON.stringify(allTopicsOrdered)};\n` +
  `export const tracks = ${JSON.stringify(buildTracks(trackDefinitions))};\n`);

const stale = [];
for (const [relativePath, contents] of outputs) {
  const destination = path.join(outputDirectory, relativePath);
  if (fs.existsSync(destination) && fs.readFileSync(destination, "utf8") === contents) continue;
  stale.push(relativePath);
  if (!checkOnly) {
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.writeFileSync(destination, contents);
  }
}
const outlinesDirectory = path.join(outputDirectory, "outlines");
if (fs.existsSync(outlinesDirectory)) {
  for (const filename of fs.readdirSync(outlinesDirectory)) {
    // Only remove obsolete generator-owned JSON files within this exact folder.
    if (!/^[a-z0-9-]+\.json$/.test(filename) || outputs.has(`outlines/${filename}`)) continue;
    stale.push(`outlines/${filename} (obsolete)`);
    if (!checkOnly) fs.unlinkSync(path.join(outlinesDirectory, filename));
  }
}
if (checkOnly && stale.length) throw new Error(`Learning artifacts are stale: ${stale.join(", ")}. Run node scripts/generate-learning-artifacts.mjs.`);
console.log(`${checkOnly ? "Verified" : "Generated"} navigation for ${allTopicsOrdered.length} topics, ${Object.keys(manifest).length} published lessons and ${outputs.size - 2} separate outlines; ${stale.length} ${checkOnly ? "stale" : "updated"} files.`);
