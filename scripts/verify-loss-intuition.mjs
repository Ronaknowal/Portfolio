import fs from 'node:fs';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { parse } from '@babel/parser';
const topicId = 'loss-functions-ce-mse-focal-contrastive-triplet';
const sourceFiles = ['src/learn/data/topics/' + topicId + '.jsx', 'src/learn/components/lesson-labs/LossIntuitionFigures.jsx', 'src/learn/components/lesson-labs/loss-intuition.css'];
const hash = file => createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const receipt = { topicId, passed: false, sourceFiles, checks: [], browser: 'pending root', independentReview: 'pending complementary reviewer' };
const save = () => fs.writeFileSync('docs/teaching/concept-intuition/' + topicId + '/author-checks.json', JSON.stringify(receipt, null, 2) + '\n');
const close = (a, b, tolerance = 1e-5) => assert.ok(Math.abs(a - b) < tolerance, `${a} != ${b}`);
save();
try {
  const quantile = estimate => [1, 2, 3, 4, 10].reduce((sum, y) => sum + (y >= estimate ? .75 * (y - estimate) : .25 * (estimate - y)), 0);
  close((quantile(3.5001) - quantile(3.4999)) / .0002, -.75);
  close((quantile(4.5001) - quantile(4.4999)) / .0002, .25);
  assert.ok(quantile(4) < quantile(3.999) && quantile(4) < quantile(4.001));
  receipt.checks.push({ name: 'Quantile arrow totals and kink optimum from independent objective differences', passed: true });
  const entropy = -.25 * Math.log(.25) - .75 * Math.log(.75);
  close(entropy, .56234); close(Math.log(2) - entropy, .13081);
  close(-Math.log(.8 * .1) / 2, 1.26286); close(-Math.log(.45), .79851); close(-Math.log(.9), .10536);
  receipt.checks.push({ name: 'Entropy/KL and multiple-positive allocation values', passed: true });
  const target = [.9 + .1 / 3, .1 / 3, .1 / 3];
  [.8, .1, .1].map((p, i) => p - target[i]).forEach((g, i) => close(g, [-.13333, .06667, .06667][i]));
  assert.ok(.99 - target[0] > 0);
  close(10 * Math.cos(Math.PI / 6), 8.6603, .00005);
  close(10 * Math.cos(2 * Math.PI / 9), 7.6604, .00005);
  close(150 + 55 * Math.cos(Math.PI / 6), 197.63, .0015);
  receipt.checks.push({ name: 'Smoothing signs and drawn angular-margin coordinates', passed: true });
  for (const file of sourceFiles.filter(file => file.endsWith('.jsx'))) parse(fs.readFileSync(file, 'utf8'), { sourceType: 'module', plugins: ['jsx'] });
  receipt.checks.push({ name: 'Changed JSX parses', passed: true });
  const baseline = JSON.parse(fs.readFileSync('docs/teaching/evidence/concept-intuition-baseline.json'));
  const preserved = Object.entries(baseline.actualFileHashes).filter(([file]) => file.startsWith('public/learn-assets/' + topicId + '/') || /^src\/learn\/data\/loss-(models|data|mechanism-program)\.js$/.test(file));
  assert.ok(preserved.length > 3);
  for (const [file, expected] of preserved) assert.equal(hash(file), expected, file);
  receipt.checks.push({ name: 'Native programs, data and prior mathematical models unchanged', passed: true, files: preserved.length });
  receipt.sourceHashes = Object.fromEntries(sourceFiles.map(file => [file, hash(file)]));
  receipt.reviewedOn = new Date().toISOString(); receipt.passed = true;
} catch (error) { receipt.failure = error.stack; process.exitCode = 1; }
save(); console.log(JSON.stringify({ passed: receipt.passed, checks: receipt.checks, failure: receipt.failure }));
