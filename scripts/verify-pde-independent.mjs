import fs from 'node:fs';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import * as m from '../src/learn/data/pde-models.js';
import { pdeExamples } from '../src/learn/data/pde-examples.js';
const directory='scratch/pde-independent-review';
fs.mkdirSync(directory,{recursive:true});
const packet=JSON.parse(fs.readFileSync('docs/teaching/evidence/pde-author-review.json','utf8'));
const sources=packet.sourceHashes.map(({path})=>({path,sha256:crypto.createHash('sha256').update(fs.readFileSync(path)).digest('hex')}));
const wave=[];
for(const time of [0,.02,.07,.37,1])for(const x of [-1.2,-1,-.7,0,.9,1,1.4])wave.push(m.waveValue(x,time,.5));
for(const time of [1e-4,1e-5,1e-6,1e-7,1e-8])for(const x of [-1,1,1-time/2,1+time/2])wave.push(m.waveValue(x,time,.5));
const heat=[.007,.017,.073,.19].map(m.heatBoundaryState);
const kernels=[];for(const time of [.13,.71])for(const alpha of [.3,1.7])kernels.push({time,alpha,values:[-.9,.17,1.23].map(x=>({x,value:m.heatKernel(x,time,alpha)}))});
const weak=[.17,.41,.83].map(m.pointSourceState);
const burgers=[];for(const left of [-2,-1,0,1,3])for(const right of [-2,0,2,3])burgers.push(m.burgersState(left,right,.37,false));
const rods=[];for(const length of [.37,.9,1.7])for(const amplitude of [0,.17,.83])for(const time of [.13,.71,2.9])rods.push(m.forcedRod(time,amplitude,.03,length));
const payload={checkedAt:new Date().toISOString(),sources,pdeExamples,wave,heat,kernels,weak,burgers,rods};
fs.writeFileSync(directory+'/current-payload.json',JSON.stringify(payload,null,2));
const run=spawnSync('scratch/lesson-tools/Scripts/python.exe',['scripts/verify-pde-independent.py'],{encoding:'utf8',maxBuffer:8e6});
process.stdout.write(run.stdout);process.stderr.write(run.stderr);process.exitCode=run.status;
