// Keep complete definition text, including decorators and comments. The existing
// displayed examples remain the sole authoring owners of these mechanisms.
const extract = String.raw`import ast, json, sys
records = json.load(sys.stdin)
pieces, definitions, imports = [], {}, set()
for record in records:
    code = record['code']
    lines = code.splitlines()
    for statement in ast.parse(code).body:
        if isinstance(statement, (ast.Import, ast.ImportFrom)):
            text = ast.get_source_segment(code, statement)
            if text not in imports:
                pieces.append(text)
                imports.add(text)
        elif isinstance(statement, (ast.FunctionDef, ast.ClassDef)):
            start = min([statement.lineno] + [d.lineno for d in statement.decorator_list])
            text = '\n'.join(lines[start - 1:statement.end_lineno])
            if statement.name in definitions:
                if ast.dump(ast.parse(text)) != ast.dump(ast.parse(definitions[statement.name])):
                    raise ValueError('Conflicting definition: ' + statement.name)
            else:
                definitions[statement.name] = text
                pieces.append(text)
print('\n\n'.join(pieces))
`;

export async function collectExamples() {
  return Promise.all(bridges.map(async ([id, stem, keys]) => {
    const owner = `src/learn/data/${stem}-examples.js`;
    const examples = Object.values(await import(pathToFileURL(path.join(root, owner))))[0];
    return { id, stem, owner, examples, keys };
  }));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const python = process.env.LESSON_PYTHON || path.join(root, 'scratch/lesson-tools/Scripts/python.exe');
  for (const { id, stem, owner, examples, keys } of await collectExamples()) {
    const result = spawnSync(python, ['-c', extract], {
      input: JSON.stringify(keys.map(key => examples[key])), encoding: 'utf8',
    });
    if (result.status !== 0) throw new Error(result.stderr);
    const directory = path.join(root, 'public/learn-assets', id);
    fs.mkdirSync(directory, { recursive: true });
    const source = `# Generated by scripts/build-dsa-library-bridges.mjs\n# Owner: ${owner}; examples: ${keys.join(', ')}\n# Rebuild; do not maintain a second hand-edited implementation here.\n\n${result.stdout}`;
    const destination = path.join(directory, `${stem.replaceAll('-', '_')}_mechanisms.py`);
    if (process.argv.includes('--check')) {
      if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== source) {
        throw new Error(`Stale mechanism download: ${destination}`);
      }
    } else fs.writeFileSync(destination, source);
    console.log(`${id}: ${keys.length} existing program owners`);
  }
}
