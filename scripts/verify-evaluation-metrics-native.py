"""Execute both learner-download programs, compare prepared fixtures, retain measured evidence."""
from pathlib import Path
import contextlib
import hashlib
import io
import json
import platform
import runpy
import numpy as np
import sklearn

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'public/learn-assets/evaluation-metrics'
DRAFT = ROOT / 'docs/teaching/drafts/evaluation-metrics-precision-recall-f1-auc-roc-ap-r-mae'

def compare(actual, expected, path='root'):
    if isinstance(expected, dict):
        assert actual.keys() == expected.keys(), path
        for key in expected: compare(actual[key], expected[key], path+'.'+key)
    elif isinstance(expected, list):
        assert len(actual) == len(expected), path
        for index, (a, e) in enumerate(zip(actual, expected)): compare(a, e, f'{path}[{index}]')
    elif isinstance(expected, (float, int)) and not isinstance(expected, bool):
        assert np.isclose(actual, expected, rtol=1e-10, atol=1e-12), (path, actual, expected)
    else:
        assert actual == expected, (path, actual, expected)

stdout = {}
for script, output in [('metrics-calculations.py', 'metric-fixtures.json'), ('banknote-evaluation.py', 'banknote-evaluation-results.json')]:
    assert (ASSETS/script).read_bytes() == (DRAFT/script).read_bytes()
    capture = io.StringIO()
    with contextlib.redirect_stdout(capture):
        runpy.run_path(str(ASSETS/script), run_name='__main__')
    stdout[script] = capture.getvalue()
    compare(json.loads((ASSETS/output).read_text()), json.loads((DRAFT/output).read_text()))

measured = json.loads((ASSETS/'banknote-evaluation-results.json').read_text())
fixture = json.loads((ASSETS/'metric-fixtures.json').read_text())
assert measured['reports']['fixed_0.5']['cost_fp1_fn5'] == 24
assert measured['reports']['development_selected']['cost_fp1_fn5'] == 26
assert set(measured['source_rows']['train']).isdisjoint(measured['source_rows']['test'])
assert len(set(sum(measured['source_rows'].values(), []))) == 480
compact = {key: measured[key] for key in ['development_thresholds', 'selected_development_record', 'reports']}
(ROOT/'src/learn/data/evaluation-metrics-data.json').write_text(json.dumps(compact, indent=2, allow_nan=False)+'\n', encoding='utf-8')
# Source display is byte-equivalent apart from platform line endings. No public raw imports.
examples = {
    'calculations': {'code': (ASSETS/'metrics-calculations.py').read_text(encoding='utf-8'), 'expected': stdout['metrics-calculations.py']},
    'evaluation': {'code': (ASSETS/'banknote-evaluation.py').read_text(encoding='utf-8'), 'expected': stdout['banknote-evaluation.py']},
}
(ROOT/'src/learn/data/evaluation-metrics-examples.js').write_text('// Generated by verify-evaluation-metrics-native.py from executed learner downloads.\nexport const evaluationMetricsExamples = '+json.dumps(examples, ensure_ascii=True, indent=2)+';\n', encoding='utf-8')
record = {'status': 'passed', 'python': platform.python_version(), 'numpy': np.__version__, 'sklearn': sklearn.__version__, 'checks': ['Both exact downloadable programs executed', 'All prepared fixtures and real prediction arrays reproduced recursively at 1e-10 relative tolerance', 'Library agreement assertions in complete calculation program passed', '480 source IDs disjoint across data roles', 'Selected policy test cost 26, fixed 0.5 test cost 24'], 'stdout': stdout, 'inputHashes': {f: hashlib.sha256((ASSETS/f).read_bytes()).hexdigest() for f in ['metrics-calculations.py', 'banknote-evaluation.py', 'banknote-subset.csv']}}
(ROOT/'docs/teaching/evidence/evaluation-metrics-native.json').write_text(json.dumps(record, indent=2)+'\n', encoding='utf-8')
